// ============================================================================
// source2/tier1/interface.rs —— 接口注册节点（InterfaceReg）的内存布局
//
// ----------------------------------------------------------------------------
// 🎓 概念卡 ㉖：struct + impl（结构体与它的方法）
// ----------------------------------------------------------------------------
// 【是什么】struct 打包数据，impl 给它挂方法。字段用 变量.字段 访问。
// 【最小示例】
//   struct Point { x: f32, y: f32 }          // 只有数据
//   impl Point {                              // impl 块里写方法
//       fn distance(&self) -> f32 { (self.x * self.x + self.y * self.y).sqrt() }
//   }
//   let p = Point { x: 3.0, y: 4.0 };
//   p.distance()                               // → 5.0（&self = 借用自己）
// ----------------------------------------------------------------------------
// 🎓 概念卡 ㉗：#[repr(C)]、unsafe、Pod、Pointer64（"照着游戏内存画结构"）
// ----------------------------------------------------------------------------
// 【#[repr(C)] 是什么】Rust 默认不保证结构体字段在内存里的顺序（可能重排）。
// #[repr(C)] 强制"按 C 语言的规则排布"：字段顺序、对齐都确定。
// 这是"照着游戏内存里的真实布局画一个一模一样的结构体"的前提。
// 【unsafe 是什么】跨进程读内存、按联合体解释字节……这些 Rust 编译器
// 无法替你证明安全。unsafe 块/impl 表示"我向编译器担保这里没问题"，
// 责任在程序员。注意：unsafe 不是"禁用安全检查"，而是"信任我"。
// 【Pod 是什么】memflow 定义的 trait：表示"这个类型就是一堆可以整块从
// 进程内存拷来拷去的字节"（类似 C++ 的 trivially copyable）。
// 【Pointer64<T> 是什么】"目标进程里"的 64 位指针。它不能直接解引用
// （那是本地指针），必须用 mem.read_ptr() 从游戏进程内存里读它指向的内容。
// 【最小示例（定义一个与游戏内存对齐的结构体）】
//   #[repr(C)]
//   struct Node { pub next: Pointer64<Node>, pub value: i32 }
//   // 之后：let n: Node = mem.read_ptr(addr).data_part()?;  // 从游戏内存读
// 【自己动手要点】
// 1) 每个字段后的 // 0x0008 是相对结构体开头的字节偏移——这是逆向的结果，
//    写错一个字段整个读取就废了；
// 2) 读游戏内存时，先读"指针字段"（Pointer64），再按需解引用，别一次读完；
// 3) 新增结构体时：先确认游戏真实布局（IDA/CheatEngine），再写 #[repr(C)]。
// ----------------------------------------------------------------------------
//
// 【这个结构体是什么】
// Source 2 引擎里，每个对外接口在内存里对应一个 InterfaceReg 节点：
//   - create_fn：创建该接口实例的函数指针；
//   - name：接口名字（C 字符串）的指针；
//   - next：链表里下一个节点（接口们串成一条单链表）。
// 顺着 next 遍历就能枚举出一个模块导出的所有接口（见 analysis/interfaces.rs）。
//
// 【概念速览】#[repr(C)] / Pod / Pointer64 / unsafe 见上方 🎓 概念卡 ㉖㉗
// （完整索引见《搭建路线图与概念索引.md》）。
// ============================================================================

use memflow::prelude::v1::*;

#[derive(Pod)]
#[repr(C)]
pub struct InterfaceReg {
    pub create_fn: Pointer64<()>,      // 0x0000 创建实例的函数指针
    pub name: Pointer64<ReprCString>,  // 0x0008 接口名字指针
    pub next: Pointer64<InterfaceReg>, // 0x0010 链表下一个节点
}
